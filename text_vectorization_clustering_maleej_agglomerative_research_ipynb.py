import pandas as pd
import numpy as np
import re
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.feature_extraction.text import CountVectorizer, TfidfVectorizer
from sklearn.cluster import AgglomerativeClustering
from sklearn.decomposition import TruncatedSVD , PCA
from sklearn.preprocessing import normalize
from sklearn.metrics import (
    silhouette_score,
    adjusted_rand_score,
    normalized_mutual_info_score
)

from gensim.models import Word2Vec

# Load Maalej dataset
df = pd.read_excel("Maalej Dataset.xlsx")

# Remove rows with missing reviews or task labels
df = df.dropna(subset=["review", "task"]).copy()

# Convert reviews to lowercase and remove punctuation
def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"[^a-zA-Z\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text

df["clean_review"] = df["review"].apply(clean_text)

# Remove empty reviews
df = df[df["clean_review"] != ""].copy()

# Actual labels
true_labels = df["task"].astype(str)

print("Dataset shape:", df.shape)
print("Task categories:")
print(true_labels.value_counts())

bow_vectorizer = CountVectorizer(max_features=3000)

X_bow = bow_vectorizer.fit_transform(df["clean_review"])

# Reduce dimensions because Agglomerative Clustering
# works with dense feature arrays in this implementation
svd_bow = TruncatedSVD(n_components=100, random_state=42)

X_bow_reduced = svd_bow.fit_transform(X_bow)

X_bow_reduced = normalize(X_bow_reduced)

print("BoW shape:", X_bow_reduced.shape)

tfidf_vectorizer = TfidfVectorizer(max_features=3000)

X_tfidf = tfidf_vectorizer.fit_transform(df["clean_review"])

# Dimensionality reduction
svd_tfidf = TruncatedSVD(n_components=100, random_state=42)

X_tfidf_reduced = svd_tfidf.fit_transform(X_tfidf)

X_tfidf_reduced = normalize(X_tfidf_reduced)

print("TF-IDF shape:", X_tfidf_reduced.shape)

# Tokenize reviews
sentences = [
    review.split()
    for review in df["clean_review"]
]

# Train Word2Vec model
w2v_model = Word2Vec(
    sentences=sentences,
    vector_size=100,
    window=5,
    min_count=1,
    workers=4,
    sg=1,
    epochs=30,
    seed=42
)

# Convert each review into an average Word2Vec vector
def get_review_vector(words, model):
    vectors = [
        model.wv[word]
        for word in words
        if word in model.wv
    ]

    if len(vectors) == 0:
        return np.zeros(model.vector_size)

    return np.mean(vectors, axis=0)

X_word2vec = np.array([
    get_review_vector(words, w2v_model)
    for words in sentences
])

X_word2vec = normalize(X_word2vec)

print("Word2Vec shape:", X_word2vec.shape)
# Store the three representations
representations = {
    "BoW": X_bow_reduced,
    "TF-IDF": X_tfidf_reduced,
    "Word2Vec": X_word2vec
}
print("All three representations created successfully!")

# Agglomerative Clustering for BoW
bow_clustering = AgglomerativeClustering(
    n_clusters=4,
    linkage="ward"
)

predicted_bow = bow_clustering.fit_predict(X_bow_reduced)


# Agglomerative Clustering for TF-IDF
tfidf_clustering = AgglomerativeClustering(
    n_clusters=4,
    linkage="ward"
)

predicted_tfidf = tfidf_clustering.fit_predict(X_tfidf_reduced)


# Agglomerative Clustering for Word2Vec
word2vec_clustering = AgglomerativeClustering(
    n_clusters=4,
    linkage="ward"
)

predicted_word2vec = word2vec_clustering.fit_predict(X_word2vec)

def evaluate_clustering(X, true_labels, predicted_labels):

    silhouette = silhouette_score(
        X,
        predicted_labels,
        sample_size=min(1000, X.shape[0]),
        random_state=42
    )

    ari = adjusted_rand_score(
        true_labels,
        predicted_labels
    )

    nmi = normalized_mutual_info_score(
        true_labels,
        predicted_labels
    )

    return silhouette, ari, nmi


# Evaluate BoW
bow_results = evaluate_clustering(
    X_bow_reduced,
    true_labels,
    predicted_bow
)

# Evaluate TF-IDF
tfidf_results = evaluate_clustering(
    X_tfidf_reduced,
    true_labels,
    predicted_tfidf
)

# Evaluate Word2Vec
word2vec_results = evaluate_clustering(
    X_word2vec,
    true_labels,
    predicted_word2vec
)

results = pd.DataFrame({
    "Vectorization Method": ["BoW", "TF-IDF", "Word2Vec"],
    "Silhouette Score": [
        bow_results[0],
        tfidf_results[0],
        word2vec_results[0]
    ],
    "ARI": [
        bow_results[1],
        tfidf_results[1],
        word2vec_results[1]
    ],
    "NMI": [
        bow_results[2],
        tfidf_results[2],
        word2vec_results[2]
    ]
})

print(results)

results.to_excel(
    "Maalej_Agglomerative_Results.xlsx",
    index=False
)

# Plot Silhouette, ARI and NMI scores
metrics = [
    "Silhouette Score",
    "ARI",
    "NMI"
]

for metric in metrics:

    plt.figure(figsize=(7, 5))

    plt.bar(
        results["Vectorization Method"],
        results[metric]
    )

    plt.title("Agglomerative Clustering - " + metric)
    plt.xlabel("Vectorization Method")
    plt.ylabel(metric)

    plt.tight_layout()
    plt.show()

cluster_results = {
    "BoW": predicted_bow,
    "TF-IDF": predicted_tfidf,
    "Word2Vec": predicted_word2vec
}

for method, labels in cluster_results.items():

    counts = pd.Series(labels).value_counts().sort_index()

    plt.figure(figsize=(7, 5))

    plt.bar(
        counts.index.astype(str),
        counts.values
    )

    plt.title(method + " - Agglomerative Cluster Distribution")
    plt.xlabel("Cluster")
    plt.ylabel("Number of Reviews")

    plt.tight_layout()
    plt.show()

fig, axes = plt.subplots(1, 3, figsize=(18, 5))

for ax, (method, X) in zip(
    axes, representations.items()
):

    if method in ["BoW", "TF-IDF"]:
        reducer = TruncatedSVD(
            n_components=2,
            random_state=42
        )
    else:
        reducer = PCA(
            n_components=2,
            random_state=42
        )

    reduced = reducer.fit_transform(X)

    sns.scatterplot(
        x=reduced[:, 0],
        y=reduced[:, 1],
        hue=cluster_results[method],
        palette="tab10",
        s=20,
        alpha=0.7,
        legend=False,
        ax=ax
    )

    ax.set_title(method + " Clustering")
    ax.set_xlabel("Dimension 1")
    ax.set_ylabel("Dimension 2")

plt.suptitle(
    "Visualization of Mobile App Review Clusters"
)
plt.tight_layout()
plt.show()
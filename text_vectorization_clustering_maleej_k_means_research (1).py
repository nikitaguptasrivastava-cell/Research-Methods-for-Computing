"""Words2Vec : We will train Word2Vec on your actual mobile app reviews and represent each review by averaging its word vectors"""

#Tokenize reviews
tokenized_reviews = [
    [ word for word in review.split()
      if word not in custom_stopwords]
    for review in reviews
]

# Train Word2Vec
w2v_model = Word2Vec(
    sentences = tokenized_reviews,
    vector_size = 1000,
    window = 5,
    min_count=1,
    workers=4,
    sg=1,
    epochs=30,
    seed=42
)

#Average word vectors for each review
def document_vector(words,model):
    vectors = [
        model.wv[word]
        for word in words
        if word in model.wv
    ]

    if len(vectors) == 0:
        return np.zeros(model.vector_size)

    return np.mean(vectors,axis=0)

X_w2v = np.array([
    document_vector(words, w2v_model)
    for words in tokenized_reviews
])

print("Word2Vec matrix shape:", X_w2v.shape)
